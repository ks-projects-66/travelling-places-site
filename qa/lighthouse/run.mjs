/**
 * Site-wide Lighthouse via Unlighthouse, mobile then desktop, against a local preview of dist/.
 *
 * Uses port 4323 so it never collides with the Playwright suite on 4322 (see qa/README.md on why
 * 4321 is avoided). Writes qa/reports/lighthouse/{mobile,desktop}/ and a summary table at
 * qa/reports/LIGHTHOUSE.md. Exit code is 0 unless a run fails outright: scores are reported, not
 * enforced.
 */

import { spawn, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTES } from '../routes.js';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');
const OUT = join(ROOT, 'qa', 'reports', 'lighthouse');
const PORT = 4323;
const SITE = `http://127.0.0.1:${PORT}`;

const server = spawn('node', ['node_modules/astro/astro.js', 'preview', '--host', '127.0.0.1', '--port', String(PORT)], {
  cwd: ROOT,
  stdio: 'ignore',
});

const ready = async () => {
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(`${SITE}/`)).ok) return;
    } catch {}
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`qa/lighthouse: preview on ${PORT} did not come up`);
};

const CATEGORIES = ['performance', 'accessibility', 'best-practices', 'seo'];
const rows = [];
let failed = false;

try {
  await ready();
  rmSync(OUT, { recursive: true, force: true });

  for (const device of ['mobile', 'desktop']) {
    const outputPath = join(OUT, device);
    const res = spawnSync(
      'node',
      [
        'node_modules/unlighthouse/bin/unlighthouse-ci.mjs',
        '--config-file', 'qa/lighthouse/unlighthouse.config.mjs',
        '--site', SITE,
        '--urls', ROUTES.join(','),
        `--${device}`,
        '--reporter', 'jsonExpanded',
        '--build-static',
        '--output-path', outputPath,
      ],
      { cwd: ROOT, stdio: 'inherit' },
    );
    if (res.status !== 0) failed = true;

    const report = join(outputPath, 'ci-result.json');
    if (!existsSync(report)) continue;
    const data = JSON.parse(readFileSync(report, 'utf8'));
    for (const r of data.routes ?? []) {
      const score = (c) => {
        const v = r.categories?.[c]?.score;
        return typeof v === 'number' ? Math.round(v * 100) : 'n/a';
      };
      const metric = (m) => r.metrics?.[m]?.displayValue ?? 'n/a';
      rows.push([device, r.path, ...CATEGORIES.map(score), metric('largest-contentful-paint'), metric('cumulative-layout-shift')]);
    }
  }
} finally {
  server.kill();
}

const table = [
  `| Device | Route | ${CATEGORIES.join(' | ')} | LCP | CLS |`,
  `|---|---|${CATEGORIES.map(() => '---').join('|')}|---|---|`,
  ...rows.map((r) => `| ${r.join(' | ')} |`),
].join('\n');

writeFileSync(
  join(ROOT, 'qa', 'reports', 'LIGHTHOUSE.md'),
  `# Lighthouse, every route\n\nGenerated by \`pnpm qa:lighthouse\` on ${new Date().toISOString().slice(0, 10)} ` +
    `against a local preview of \`dist/\`. Average of 3 samples per route, unthrottled, so treat performance as relative rather than field data. Scores are reported, not ` +
    `enforced. Browse the full reports at \`qa/reports/lighthouse/<device>/client/index.html\`.\n\n${table}\n`,
);
console.log(`\n${table}\n`);
process.exit(failed ? 1 : 0);
